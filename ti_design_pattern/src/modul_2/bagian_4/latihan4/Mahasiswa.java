package modul_2.bagian_4.latihan4;

public class Mahasiswa {
    // Atribut dengan akses private
    private String nama;
    private String nim;

    // Setter untuk nama
    public void setNama(String nama) {
        this.nama = nama;
    }

    // Getter untuk nama
    public String getNama() {
        return nama;
    }

    // Setter untuk nim
    public void setNim(String nim) {
        this.nim = nim;
    }

    // Getter untuk nim
    public String getNim() {
        return nim;
    }
}